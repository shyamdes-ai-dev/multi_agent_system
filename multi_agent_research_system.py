if __name__ == "__main__":
    print("==========================================================")
    print(" Multi-Agent Autonomous Research System (LangGraph) ")
    print("==========================================================")

    # Initialize research workflow
    app = create_research_system()

    # Define research prompt
    topic_input = "Impact of Quantum Computing on Modern Cryptography"

    initial_state = {
        "topic": topic_input,
        "messages": [],
        "findings": [],
        "search_queries": [],
        "analysis": "",
        "report": "",
        "quality_score": 0.0,
        "quality_feedback": "",
        "iteration": 0,
    }

    # Execute workflow graph
    final_output = app.invoke(initial_state)

    print("\n==========================================================")
    print(" FINAL GENERATED RESEARCH REPORT ")
    print("==========================================================")
    print(final_output["report"])
    print(f"\nFinal Quality Score: {final_output['quality_score']}/10.0")
